#!/usr/bin/env bash
# Persistent CPU/GPU pill visibility without a Waybar process/config reload.
# Waybar receives empty stat text and hides those widgets automatically;
# a watched CSS import removes the now-empty group's border/padding.
set -euo pipefail

action="${1:-}"
root="${XDG_STATE_HOME:-$HOME/.local/state}/waybar"
pill_dir="$root/pill-visibility"
graph_dir="$root/graph-toggles"
config="${WAYBAR_CONFIG:-$HOME/.config/waybar/config.jsonc}"
style="${WAYBAR_STYLE:-$HOME/.config/waybar/style.css}"
css="${WAYBAR_STYLE_VISIBILITY_CSS:-$HOME/.config/waybar/stats-pill-visibility.css}"
menu_xml="${WAYBAR_MENU_XML:-$HOME/.config/waybar/menus/stats-menu.xml}"

# This file is imported by style.css and automatically monitored by Waybar.
# It must update in-place: a rename can invalidate older GTK file monitors.
# The doubled ID selector overrides later single-ID selectors in style.css.
write_css() {
  local rules='/* Generated by stats-menu.sh. Do not edit; use stats-menu.sh sync. */'
  local pill
  for pill in cpu gpu; do
    if [[ -f "$pill_dir/$pill.hidden" ]]; then
      rules+=$'\n'
      rules+="#${pill}-pill#${pill}-pill {"
      rules+=$'\n'
      rules+='  background: transparent; border: none; border-radius: 0px;'
      rules+=$'\n'
      rules+='  margin: 0px; padding: 0px; min-width: 0px; min-height: 0px;'
      rules+=$'\n'
      rules+='}'
    fi
  done
  rules+=$'\n'
  mkdir -p "$(dirname "$css")"
  # Avoid unnecessarily triggering the CSS watcher when nothing changed.
  if [[ -r "$css" ]] && [[ "$(cat "$css")" == "${rules%$'\n'}" ]]; then
    return
  fi
  printf '%s' "$rules" > "$css"
}

check_files() {
  local fail=0
  for path in "$config" "$style" "$menu_xml"; do
    if [[ -r "$path" ]]; then printf 'OK: %s\n' "$path";
    else printf 'MISSING: %s\n' "$path" >&2; fail=1; fi
  done
  if [[ -r "$config" ]]; then
    if ! jq -e '
      .[0] as $bar |
      ($bar["modules-right"] | index("group/cpu-pill") != null) and
      ($bar["modules-right"] | index("group/gpu-pill") != null) and
      ([ $bar["group/cpu-pill"].modules[], $bar["group/gpu-pill"].modules[] ] |
         all(.[]; $bar[.]["format"] == "{}"))
    ' "$config" >/dev/null 2>&1; then
      printf 'ERROR: both groups and their dynamic text formats must be installed\n' >&2
      fail=1
    fi
  fi
  if [[ -r "$style" ]] && ! grep -Fq '@import "stats-pill-visibility.css";' "$style"; then
    printf 'ERROR: missing CSS import in %s\n' "$style" >&2; fail=1
  fi
  if [[ -r "$config" ]] && ! jq -e '.[0].reload_style_on_change == true' "$config" >/dev/null; then
    printf 'ERROR: reload_style_on_change must be enabled\n' >&2; fail=1
  fi
  if [[ ! -r "$css" ]]; then
    printf 'MISSING: generated CSS %s (run stats-menu.sh sync)\n' "$css" >&2; fail=1
  fi
  return "$fail"
}

case "$action" in
  cpu|gpu)
    mkdir -p "$pill_dir"
    file="$pill_dir/$action.hidden"
    if [[ -e "$file" ]]; then rm -f -- "$file"; else : > "$file"; fi
    write_css
    ;;
  graphs)
    mkdir -p "$graph_dir"
    metrics=(cpu memory cpu-clock-avg cpu-clock-max cpu-temp gpu-usage gpu-core-clock gpu-vram-usage gpu-vram-clock gpu-power gpu-temp)
    all_hidden=true
    for metric in "${metrics[@]}"; do
      if [[ ! -e "$graph_dir/$metric.hidden" ]]; then all_hidden=false; break; fi
    done
    for metric in "${metrics[@]}"; do
      if [[ "$all_hidden" == true ]]; then rm -f -- "$graph_dir/$metric.hidden"
      else : > "$graph_dir/$metric.hidden"; fi
    done
    ;;
  sync)
    write_css
    ;;
  status)
    for pill in cpu gpu; do
      if [[ -e "$pill_dir/$pill.hidden" ]]; then printf '%s: hidden\n' "$pill"
      else printf '%s: visible\n' "$pill"; fi
    done
    ;;
  check)
    command -v jq >/dev/null || { echo 'ERROR: jq required' >&2; exit 1; }
    check_files
    ;;
  *) printf 'Usage: %s {cpu|gpu|graphs|sync|status|check}\n' "$0" >&2; exit 2 ;;
esac
